def load_policy_rates(index: pd.DatetimeIndex | None = None) -> pd.DataFrame:
    """Return a DataFrame of daily policy rates (%) per currency.

    If *index* is provided the result is reindexed and forward-filled to match it.
    """
    series: dict[str, pd.Series] = {}
    for ccy, changes in _RATES.items():
        dates = pd.to_datetime([d for d, _ in changes])
        values = [v for _, v in changes]
        s = pd.Series(values, index=dates, dtype=float)
        series[ccy] = s

    df = pd.DataFrame(series).sort_index()

    if index is not None:
        full_idx = df.index.union(index).sort_values()
        df = df.reindex(full_idx).ffill().reindex(index)

    return df
